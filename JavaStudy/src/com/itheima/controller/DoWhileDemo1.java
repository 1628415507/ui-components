package com.itheima.loopdowhile;

public class DoWhileDemo1 {
    public static void main(String[] args) {
        /*
         * 
         * 利用do... while循环，输出5行 "hello world"
         * 
         * 注：do... while循环，熟悉语法即可，无需额外练习
         * 
         * 特点：先执行后判断，循环体至少执行一次
         * 
         * for,while 的特点： 先判断后执行
         * 
         */

        /*
         * int i = 10;
         * do{
         * System.out.println("Hello World!");
         * i++;
         * }while (i <= 5);
         */

        for (int j = 10; j <= 5; j++) {
            System.out.println("Hello World!");
        }

    }
}
